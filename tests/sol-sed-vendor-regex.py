#!/usr/bin/env python3
"""Reproduce sed's private regex header from the pinned GNU sed 4.9 archive.

Usage: python3 tests/sol-sed-vendor-regex.py sed-4.9.tar.xz
No network or compiler is invoked. See docs/sol-sed-regex.md.
"""
import hashlib
from pathlib import Path
import re
import sys
import tarfile

archive = Path(sys.argv[1])
assert hashlib.sha256(archive.read_bytes()).hexdigest() == '6e226b732e1cd739464ad6862bd1a1aba42d7982922da7a53519631d24975181'
with tarfile.open(archive) as tar:
    def read(name):
        return tar.extractfile('sed-4.9/lib/'+name).read().decode()
    parts = {name: read(name) for name in ('regex.h','regex_internal.h','regex_internal.c','regcomp.c','regexec.c')}
# Only this translation unit sees the engine. Public functions and syntax
# state are static; names also receive a prefix to avoid libc interposition.
parts['regex.h'] = re.sub(r'^extern (?!"C")', 'static ', parts['regex.h'], flags=re.M)
parts['regcomp.c'] = parts['regcomp.c'].replace('reg_syntax_t re_syntax_options;', 'static reg_syntax_t re_syntax_options;')
for inc in ('# include <dynarray.h>', '#include <intprops.h>', '#include <verify.h>', '# include "attribute.h"'):
    assert inc in parts['regex_internal.h']
    parts['regex_internal.h'] = parts['regex_internal.h'].replace(inc, '')
# set_regs uses dynarray only as a once-sized temporary capture array. Keep
# all failure/cleanup branches, with a checked allocation instead of importing
# gnulib's unrelated general-purpose dynarray implementation and globals.
s = parts['regexec.c']
a = s.index('#define DYNARRAY_STRUCT  regmatch_list')
b = s.index('/* Set the positions', a)
s = s[:a] + s[b:]
s = s.replace('  struct regmatch_list prev_match;\n  regmatch_list_init (&prev_match);', '  regmatch_t *prev_idx_match;')
s = s.replace('  if (!regmatch_list_resize (&prev_match, nmatch))',
'''  prev_idx_match = nmatch > SIZE_MAX / sizeof *prev_idx_match ? NULL
    : malloc (nmatch * sizeof *prev_idx_match);
  if (prev_idx_match == NULL)''')
s = s.replace('regmatch_list_free (&prev_match);', 'free (prev_idx_match);')
s = s.replace('  regmatch_t *prev_idx_match = regmatch_list_begin (&prev_match);\n', '')
assert 'regmatch_list' not in s
parts['regexec.c'] = s
symbols = ('regex_t regmatch_t regoff_t reg_syntax_t re_pattern_buffer re_registers '
           're_syntax_options re_set_syntax re_compile_pattern re_compile_fastmap '
           're_search re_search_2 re_match re_match_2 re_set_registers '
           'regcomp regexec regerror regfree').split()
prefix = '''/* Generated by tests/sol-sed-vendor-regex.py from GNU sed 4.9.
   The upstream files below are LGPL-2.1-or-later; their notices are retained.
   Local integration: private symbols, compiler compatibility definitions,
   checked temporary capture allocation. See docs/sol-sed-regex.md. */
#ifndef BASHOS_SED_REGEX_H
#define BASHOS_SED_REGEX_H
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <limits.h>
#include <assert.h>
#ifndef __glibc_likely
# define __glibc_likely(x) __builtin_expect (!!(x), 1)
# define __glibc_unlikely(x) __builtin_expect (!!(x), 0)
#endif
#ifndef __glibc_has_attribute
# define __glibc_has_attribute(x) __has_attribute (x)
#endif
#ifndef __attribute_warn_unused_result__
# define __attribute_warn_unused_result__ __attribute__ ((warn_unused_result))
#endif
#ifndef __attribute_noinline__
# define __attribute_noinline__ __attribute__ ((noinline))
#endif
#ifndef __always_inline
# define __always_inline inline __attribute__ ((__always_inline__))
#endif
#define TYPE_SIGNED(t) ((t) -1 < (t) 0)
#define INT_ADD_WRAPV(a,b,r) __builtin_add_overflow (a,b,r)
#define assume(x) do { if (!(x)) __builtin_unreachable (); } while (0)
#define verify(x) _Static_assert (x, #x)
#define GNULIB_REGEX_SINGLE_THREAD 1
#define weak_alias(a,b)
#define libc_hidden_def(a)
#define libc_hidden_proto(a)
#ifndef FALLTHROUGH
# define FALLTHROUGH __attribute__ ((fallthrough))
#endif
'''
prefix += ''.join(f'#define {name} bs_sed_{name}\n' for name in symbols)
text = prefix + '\n'.join('/* Upstream lib/'+name+' */\n'+body for name, body in parts.items())+'''
/* Bash supplies its own TYPE_SIGNED after including this private engine. */
#undef TYPE_SIGNED
#endif /* BASHOS_SED_REGEX_H */
'''
root = Path(__file__).resolve().parents[1]
(root/'loadables/common/sed-regex.h').write_text(text)
print('generated', len(text), 'bytes')
